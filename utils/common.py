def get_respond(model_name, model_type, mode, seed, dtype=torch.bfloat16):
    if model_type == 'huggingface':
        tokenizer = AutoTokenizer.from_pretrained(
            model_name,
            padding_side="right",
            use_fast=False,
            trust_remote_code=True,
        )

        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            dtype=dtype,
            device_map="auto",
            trust_remote_code=True
        ).to("cuda")
        model.eval()

        if tokenizer.pad_token is None:
            tokenizer.add_special_tokens({'pad_token': '[PAD]'})
            model.config.pad_token_id = tokenizer.pad_token_id
            model.resize_token_embeddings(len(tokenizer))

        if mode == "gen":
            def respond(messages_batch):
                
                inputs = tokenizer.apply_chat_template(
                    messages_batch,
                    add_generation_prompt=True,
                    return_tensors="pt",
                    padding=True,
                    enable_thinking=False
                ).to("cuda")
                with torch.no_grad():
                    output = model.generate(
                        **inputs,
                        max_length=1024
                    )
                out_batch = tokenizer.batch_decode(output[:, inputs["input_ids"].shape[-1]:], skip_special_tokens=True)
                out_batch = [sample.rstrip("</s>") for sample in out_batch]

                return out_batch
        elif mode != "gen":
            def respond(messages_batch):
                # Mapping from numeric scores to their corresponding token IDs
                score_tokens = ["1", "2", "3", "4", "5"]
                score_tokens = {score: tokenizer.tokenize(score) for score in score_tokens}
                score_ids = {score: tokenizer.convert_tokens_to_ids(token)[0] for (score, token) in score_tokens.items()}
                
                inputs = tokenizer.apply_chat_template(
                    messages_batch,
                    add_generation_prompt=True,
                    return_tensors="pt",
                    padding=True,
                    enable_thinking=False
                )
                inputs = {k: v.to("cuda") for k, v in inputs.items()}
                with torch.no_grad():
                    output = model(**inputs)

                # Find the ID of the actual last token (i.e., not a padding token) for each sequence in the batch
                input_ids = inputs["input_ids"]
                padding_mask = input_ids != tokenizer.pad_token_id # (batch_size, seq_length)
                actual_seq_lens = padding_mask.int().sum(dim=1) # (batch_size,)
                last_token_indices = actual_seq_lens - 1 # (batch_size,)

                # Get the logits of the last token    
                batch_idx = torch.arange(output.logits.size(0), device="cuda")
                last_logits = output.logits[batch_idx, last_token_indices, :] # (batch_size, vocab_size)
                log_probs = torch.log_softmax(last_logits, dim=-1) # (batch_size, vocab_size)

                out_batch = []
                for idx in range(log_probs.shape[0]):
                    score_softmaxes = {int(score): torch.exp(log_probs[idx, score_id]) for (score, score_id) in score_ids.items()}

                    if mode == "max":
                        max_score = max(score_softmaxes, key=score_softmaxes.get)
                        out_batch.append(f"{max_score:.3f}")
                    elif mode == "mean":
                        sum_weight = sum(score_softmaxes.values()) # For normalization
                        mean_score = 1 / sum_weight * sum([score * weight for (score, weight) in score_softmaxes.items()])
                        out_batch.append(f"{mean_score:.3f}")
                    else:
                        print("Unrecognized generator mode:", mode)
                        exit()

                return out_batch

        return respond
    elif model_type == 'openai':
        # OpenAI client
        client = openai.Client(api_key=os.environ["OPENAI_API_KEY"])

        # Define the text completion function
        respond = lambda messages_batch: [
            client.chat.completions.create(**{
                "model": model_name,
                "max_tokens": 1024,
                "temperature": 0.0,
                "seed": seed,
                "messages": messages
            }).choices[0].message.content
            for messages in messages_batch
        ]

        return respond
    else:
        return None

def get_feature_scorer(respond, data_type):
    if data_type.startswith("cora"):
        sys_text = CORA_SYS_TEMPLATE
        user_template = CORA_USER_TEMPLATE
    elif data_type.startswith("recipe"):
        sys_text = RECIPE_SYS_TEMPLATE
        user_template = RECIPE_USER_TEMPLATE
    else:
        sys_text = None
        user_template = None

    def feature_scorer(history, reply, features):
        messages_batch = []

        feature_names = features.keys()
        for feature_name in feature_names:
            feature_data = features[feature_name]
            attribute_desc = feature_data["attribute_desc"]
            attr_min = feature_data["attr_min"]
            attr_max = feature_data["attr_max"]

            arg_dict = {
                "history": history,
                "reply": reply,
                "attribute_desc": attribute_desc,
                "attr_min": attr_min,
                "attr_max": attr_max
            }
            user_text = user_template.format(**arg_dict)
            messages = [
                {"role": "system", "content": sys_text},
                {"role": "user", "content": user_text}
            ]
            messages_batch.append(messages)

        # Perform batch inference
        out_batch = respond(messages_batch)

        # Extract scores and return them in a dictionary
        scores = {}
        for feature_name, out in zip(feature_names, out_batch):
            match = re.search(r'[-+]?\d*\.\d*|\d+', out)
            scores[feature_name] = float(match.group(0)) if match else None

        return scores

    return feature_scorer
