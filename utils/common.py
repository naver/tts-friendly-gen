def fetch_profile_desc(profile_path, data_type):
    with open(profile_path, 'r') as f:
        profile_dict = json.loads(f.read())
    profile_desc_dict = {}
    for profile in profile_dict:
        dataset_name = data_type + "-" + profile["name"]
        profile_desc_dict[dataset_name] = profile['description']

    return profile_desc_dict

